// gdvr_launch: one-click test launcher, meant to be added to Steam as a non-Steam game.
//
//   1. Backs up Grim Dawn saves (local and Steam Cloud) to %LOCALAPPDATA%\gdvr\save_backups.
//   2. Starts x64\Grim Dawn.exe (unless it is already running).
//   3. Waits for the engine to load, then injects gdvr.dll.
//
//   gdvr_launch [--game-dir "<path>"]
//
// The game files are never modified; launching Grim Dawn normally stays vanilla.

#include <windows.h>
#include <shlobj.h>
#include <shellapi.h>
#include <tlhelp32.h>

#include <algorithm>
#include <cstdio>
#include <filesystem>
#include <string>
#include <vector>

#include "../common/inject.h"
#include "gdvr_config.h"  // generated by CMake: GDVR_GAME_DIR

namespace fs = std::filesystem;

namespace {

constexpr wchar_t kDefaultGameDir[] = GDVR_GAME_DIR;  // set by CMake
constexpr wchar_t kAppId[] = L"219990";
constexpr int kBackupsToKeep = 10;
constexpr DWORD kStartTimeoutMs = 120000;

fs::path KnownFolder(REFKNOWNFOLDERID id) {
  PWSTR p = nullptr;
  fs::path out;
  if (SUCCEEDED(SHGetKnownFolderPath(id, 0, nullptr, &p))) out = p;
  CoTaskMemFree(p);
  return out;
}

std::wstring RegString(HKEY root, const wchar_t* key, const wchar_t* value) {
  wchar_t buf[MAX_PATH];
  DWORD size = sizeof(buf);
  if (RegGetValueW(root, key, value, RRF_RT_REG_SZ, nullptr, buf, &size) != ERROR_SUCCESS) return {};
  return buf;
}

std::wstring Timestamp() {
  SYSTEMTIME t;
  GetLocalTime(&t);
  wchar_t buf[32];
  swprintf_s(buf, L"%04d%02d%02d-%02d%02d%02d", t.wYear, t.wMonth, t.wDay, t.wHour, t.wMinute, t.wSecond);
  return buf;
}

// Save locations: local saves and every Steam account's cloud folder for Grim Dawn.
std::vector<std::pair<std::wstring, fs::path>> SaveSources() {
  std::vector<std::pair<std::wstring, fs::path>> out;
  out.emplace_back(L"local", KnownFolder(FOLDERID_Documents) / L"My Games" / L"Grim Dawn" / L"save");

  fs::path steam = RegString(HKEY_CURRENT_USER, L"Software\\Valve\\Steam", L"SteamPath");
  std::error_code ec;
  if (!steam.empty() && fs::exists(steam / L"userdata", ec))
    for (const auto& user : fs::directory_iterator(steam / L"userdata", ec))
      out.emplace_back(L"cloud_" + user.path().filename().wstring(), user.path() / kAppId / L"remote");
  return out;
}

void BackupSaves() {
  const fs::path root = KnownFolder(FOLDERID_LocalAppData) / L"gdvr" / L"save_backups";
  const fs::path dest = root / Timestamp();
  std::error_code ec;
  bool any = false;

  for (const auto& [name, src] : SaveSources()) {
    if (!fs::exists(src, ec) || fs::is_empty(src, ec)) continue;
    fs::create_directories(dest / name, ec);
    fs::copy(src, dest / name, fs::copy_options::recursive | fs::copy_options::overwrite_existing, ec);
    wprintf(ec ? L"  ! backup of %s failed: %S\n" : L"  backed up %s\n", src.c_str(), ec.message().c_str());
    any = true;
  }
  if (!any) {
    wprintf(L"  no saves found to back up\n");
    return;
  }
  wprintf(L"  -> %s\n", dest.c_str());

  // Keep only the newest backups (folder names are timestamps, so they sort by age).
  std::vector<fs::path> all;
  for (const auto& e : fs::directory_iterator(root, ec))
    if (e.is_directory()) all.push_back(e.path());
  std::sort(all.begin(), all.end());
  for (size_t i = 0; i + kBackupsToKeep < all.size(); ++i) fs::remove_all(all[i], ec);
}

bool IsRunning(const wchar_t* exeName) {
  HANDLE snap = CreateToolhelp32Snapshot(TH32CS_SNAPPROCESS, 0);
  PROCESSENTRY32W pe = {sizeof(pe)};
  bool found = false;
  for (BOOL ok = Process32FirstW(snap, &pe); ok && !found; ok = Process32NextW(snap, &pe))
    found = _wcsicmp(pe.szExeFile, exeName) == 0;
  CloseHandle(snap);
  return found;
}

// Starts SteamVR before the game: if it starts later, its window steals focus and a
// fullscreen game minimises and stops rendering.
void StartSteamVR() {
  if (IsRunning(L"vrcompositor.exe")) {
    wprintf(L"  already running\n");
    return;
  }
  ShellExecuteW(nullptr, L"open", L"steam://rungameid/250820", nullptr, nullptr, SW_SHOWNORMAL);
  const ULONGLONG deadline = GetTickCount64() + 60000;
  while (GetTickCount64() < deadline && !IsRunning(L"vrcompositor.exe")) Sleep(500);
  if (IsRunning(L"vrcompositor.exe")) {
    Sleep(3000);  // let its windows settle before the game takes focus
    wprintf(L"  started\n");
  } else {
    wprintf(L"  ! SteamVR did not start (headset connected?). Continuing; the mod retries every 5 s.\n");
  }
}

bool StartGame(const fs::path& gameDir) {
  const fs::path exe = gameDir / L"x64" / L"Grim Dawn.exe";
  std::wstring cmd = L"\"" + exe.wstring() + L"\"";
  STARTUPINFOW si = {sizeof(si)};
  PROCESS_INFORMATION pi = {};
  if (!CreateProcessW(exe.c_str(), cmd.data(), nullptr, nullptr, FALSE, 0, nullptr, gameDir.c_str(), &si, &pi)) {
    wprintf(L"Could not start %s (%lu)\n", exe.c_str(), GetLastError());
    return false;
  }
  CloseHandle(pi.hThread);
  CloseHandle(pi.hProcess);
  return true;
}

// Waits for a Grim Dawn process that has Engine.dll loaded and stays alive (Steam may restart
// the game once through its own launcher; that first process exits quickly).
DWORD WaitForGame() {
  const ULONGLONG deadline = GetTickCount64() + kStartTimeoutMs;
  while (GetTickCount64() < deadline) {
    DWORD pid = gdvr::inject::FindGameProcess();
    if (pid && gdvr::inject::HasModule(pid, L"Engine.dll")) {
      Sleep(3000);
      if (gdvr::inject::FindGameProcess() == pid) return pid;
      continue;
    }
    Sleep(250);
  }
  return 0;
}

int Fail(const wchar_t* msg) {
  wprintf(L"\n%s\nPress Enter to close.\n", msg);
  getwchar();
  return 1;
}

}  // namespace

int wmain(int argc, wchar_t** argv) {
  fs::path gameDir = kDefaultGameDir;
  for (int i = 1; i + 1 < argc; ++i)
    if (_wcsicmp(argv[i], L"--game-dir") == 0) gameDir = argv[i + 1];

  wprintf(L"Grim Dawn VR test launcher\n\n[1/4] Backing up saves\n");
  BackupSaves();

  wprintf(L"[2/4] Starting SteamVR\n");
  StartSteamVR();

  wprintf(L"[3/4] Starting Grim Dawn (64-bit)\n");
  if (gdvr::inject::FindGameProcess()) {
    wprintf(L"  already running\n");
  } else if (!StartGame(gameDir)) {
    return Fail(L"Start failed. Check the game path (--game-dir).");
  }

  DWORD pid = WaitForGame();
  if (!pid) return Fail(L"Grim Dawn did not finish starting within 2 minutes.");

  wprintf(L"[4/4] Loading mod\n");
  HANDLE process = OpenProcess(PROCESS_ALL_ACCESS, FALSE, pid);
  if (!process) return Fail(L"Could not open the game process.");
  const bool ok = gdvr::inject::InjectFresh(process, pid);
  CloseHandle(process);
  if (!ok) return Fail(L"Injection failed.");

  wprintf(L"\nDone. This window closes in 5 seconds.\n");
  Sleep(5000);
  return 0;
}
