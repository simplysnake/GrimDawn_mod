// gdvr_launch: starts Grim Dawn in VR. Meant to be added to Steam as its own (VR) game.
//
//   1. Finds Grim Dawn (Steam libraries) and puts the mod's dinput8.dll stand-in in its x64 folder
//      (it stays dormant unless this launcher starts the game).
//   2. Backs up the saves (local and Steam Cloud) to %LOCALAPPDATA%\gdvr\save_backups.
//   3. Swaps in the VR copy of the game's options.txt (window mode, resolution...) and puts the
//      normal one back when the game exits, so Grim Dawn started normally keeps its own settings.
//   4. Starts SteamVR, then the game with the mod, and waits until the game exits.
//
//   gdvr_launch [--game-dir "<path>"]
//
// Used by the installer (no windows; exit code 0 = done, 2 = Steam is running, 3 = no Steam, 1 = failed):
//   gdvr_launch --add-to-steam        adds "Grim Dawn VR" to Steam (listed as a VR game)
//   gdvr_launch --remove-from-steam   removes it again
//   gdvr_launch --uninstall           removes the dinput8.dll stand-in, puts the normal options.txt back,
//                                     removes the Steam entry
//   gdvr_launch --steam-roundtrip <in> <out>   reads and rewrites a shortcuts.vdf unchanged (test)
//
// No console window: progress goes to %LOCALAPPDATA%\gdvr\launcher.log, problems to a message box.

